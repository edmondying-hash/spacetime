#!/usr/bin/env python3
"""
118-Element 3D BCC Periodic Table Dashboard (`elements/plot_periodic_dashboard.py`).

Reads `periodic_118.json` (generated by `bcc_periodic_table.py --all --json periodic_118.json`)
and renders a 4-panel (2x2) visual overview (`periodic_dashboard.png`) across Z = 1..118:
  1. Nuclear Binding Curve (MeV/nucleon) with 26Fe peak and 92U fissile cliff.
  2. Relativistic 1s Speed (v/c) & Lorentz Contraction (%) across Z = 1..118 (79Au, 80Hg, 118Og).
  3. Slater Effective Nuclear Charge (Z_eff) & Shell Jumps (n = 1..7) across periods.
  4. Quark Census (Up vs. Down Quarks) & Total BCC Routing Workload (Ticks).
"""

import argparse
import json
from pathlib import Path
import matplotlib.pyplot as plt


def render_periodic_dashboard(
    json_path: str = "periodic_118.json", out_png: str = "periodic_dashboard.png"
) -> None:
    with open(json_path, "r", encoding="utf-8") as f:
        rows = json.load(f)

    z_vals = [r["Z"] for r in rows]
    bind_nuc = [r["bind_per_nucleon_mev"] for r in rows]
    beta_1s = [r["beta_1s"] for r in rows]
    contract = [r["rel_contraction_pct"] for r in rows]
    z_eff = [r["z_eff"] for r in rows]
    up_q = [r["up_quarks"] for r in rows]
    down_q = [r["down_quarks"] for r in rows]

    plt.style.use("seaborn-v0_8-darkgrid")
    fig, axes = plt.subplots(2, 2, figsize=(16, 10.5))
    ax0, ax1, ax2, ax3 = axes.flatten()

    # 1. Nuclear Binding Energy per Nucleon (Z = 1..118)
    ax0.plot(z_vals, bind_nuc, linewidth=2.3, color="#1d3557", label="SEMF Pion/Gluon Binding / Nucleon")
    ax0.axvline(26, color="#2a9d8f", linestyle="--", linewidth=1.5, label="26Fe Peak Stability (8.85 MeV/nuc)")
    ax0.axvline(92, color="#d62828", linestyle=":", linewidth=1.5, label="92U Fissile Cliff (7.63 MeV/nuc)")
    ax0.scatter([2, 26, 79, 92, 118], [bind_nuc[i - 1] for i in (2, 26, 79, 92, 118)], color="#e76f51", zorder=5)
    ax0.set_xlabel("Atomic Number Z (1 -> 118)")
    ax0.set_ylabel("Binding Energy / Nucleon (MeV)")
    ax0.set_title("1. Nuclear Binding Curve (Fusion Climb -> 26Fe -> Fission)", fontweight="bold")
    ax0.set_ylim(0, 10.0)
    ax0.legend(fontsize=8.5, loc="lower right")
    # 2. Special Relativity Inside Atoms: 1s Speed (v/c) & Lorentz Contraction (%)
    ax1_twin = ax1.twinx()
    l1 = ax1.plot(z_vals, beta_1s, linewidth=2.2, color="#219ebc", label="1s Orbital Speed (v/c = Z·α)")
    l2 = ax1_twin.plot(z_vals, contract, linewidth=2.3, linestyle="--", color="#e63946", label="Lorentz Contraction (1 - 1/γ) %")
    ax1.axvline(80, color="#1d1e2c", linestyle=":", linewidth=1.4)
    ax1_twin.annotate(
        "80Hg (18.8%)\nLiquid Metal",
        xy=(80, 18.81),
        xytext=(52, 26),
        arrowprops={"arrowstyle": "->", "color": "#1d1e2c", "lw": 1.2},
        fontsize=8.5,
        fontweight="bold",
    )
    ax1_twin.annotate(
        "118Og (49.2%)",
        xy=(118, 49.15),
        xytext=(88, 45),
        arrowprops={"arrowstyle": "->", "color": "#e63946", "lw": 1.2},
        fontsize=8.5,
        fontweight="bold",
    )
    ax1.set_xlabel("Atomic Number Z (1 -> 118)")
    ax1.set_ylabel("1s Speed Fraction (v / c)", color="#219ebc")
    ax1_twin.set_ylabel("Lorentz Contraction (%)", color="#e63946")
    ax1.set_title("2. Relativistic 1s Core Speed & Lorentz Contraction", fontweight="bold")
    lines = l1 + l2
    ax1.legend(lines, [l.get_label() for l in lines], fontsize=8.5, loc="upper left")

    # 3. Slater Effective Nuclear Charge (Z_eff) & Noble-Gas Shell Closures
    ax2.plot(z_vals, z_eff, linewidth=2.1, color="#7209b7", label="Outer Valence Z_eff")
    for noble_z, lbl in [(2, "He"), (10, "Ne"), (18, "Ar"), (36, "Kr"), (54, "Xe"), (86, "Rn"), (118, "Og")]:
        ax2.axvline(noble_z, color="#adb5bd", linestyle=":", linewidth=1.1)
        ax2.text(noble_z, z_eff[noble_z - 1] + 0.4, lbl, fontsize=8, ha="center", color="#495057", fontweight="bold")
    ax2.set_xlabel("Atomic Number Z (1 -> 118)")
    ax2.set_ylabel("Effective Nuclear Charge Z_eff")
    ax2.set_title("3. Pauli Shell Filling & Noble-Gas Screening Jumps", fontweight="bold")
    ax2.legend(fontsize=8.5, loc="upper left")

    # 4. Nuclear Quark Census: Up Quarks vs. Down Quarks (Neutron-Rich Drift)
    ax3.plot(z_vals, down_q, linewidth=2.3, color="#e07a5f", label="Down Quarks (Z + 2N)")
    ax3.plot(z_vals, up_q, linewidth=2.3, color="#2a9d8f", label="Up Quarks (2Z + N)")
    ax3.fill_between(z_vals, up_q, down_q, color="#f4a261", alpha=0.22, label="Neutron Excess (N > Z for Coulomb Stability)")
    ax3.set_xlabel("Atomic Number Z (1 -> 118)")
    ax3.set_ylabel("Total Quark Count per Atom")
    ax3.set_title("4. Quark Census Across Z = 1..118 (~98.85% Gluon Mass)", fontweight="bold")
    ax3.legend(fontsize=8.5, loc="upper left")

    fig.suptitle(
        "3D BCC Spacetime Network: Complete 118-Element Periodic Table Dashboard",
        fontsize=15,
        fontweight="bold",
    )
    plt.tight_layout()
    plt.subplots_adjust(top=0.92)
    plt.savefig(out_png, dpi=180)
    print(f"[Saved 118-element periodic dashboard -> {out_png}]")


def main() -> None:
    parser = argparse.ArgumentParser(description="Render 4-panel dashboard from periodic_118.json")
    parser.add_argument("--json", type=str, default="periodic_118.json", help="Input JSON path")
    parser.add_argument("--out", type=str, default="periodic_dashboard.png", help="Output PNG path")
    args = parser.parse_args()
    if not Path(args.json).exists():
        raise FileNotFoundError(f"{args.json} not found. Run: python3 bcc_periodic_table.py --all --json periodic_118.json")
    render_periodic_dashboard(args.json, args.out)


if __name__ == "__main__":
    main()
